def test_shared_axis_flip_preserves_full_volume_ssc4_metric(tmp_path):
    affine = np.diag([-2.0, 3.0, 5.0, 1.0])
    image = np.arange(60, dtype=np.float32).reshape(3, 4, 5)
    truth = np.zeros(image.shape, dtype=np.uint8)
    truth[0, 1, 2] = 1
    for name, array in [("image", image), ("truth", truth), ("ssc4", truth)]:
        nib.save(nib.Nifti1Image(array, affine), tmp_path / f"{name}.nii.gz")
    case = load_case(
        tmp_path / "image.nii.gz",
        tmp_path / "truth.nii.gz",
        {"SSC4": (tmp_path / "ssc4.nii.gz", 1)},
    )
    assert case["scores"].iloc[0].Dice == 1
    assert case["masks"]["Reference"][2, 1, 2]
    assert np.array_equal(case["masks"]["Reference"], case["masks"]["SSC4"])
    assert np.array_equal(case["spacing"], [2, 3, 5])


def test_geometry_mismatch_fails_instead_of_silently_resampling(tmp_path):
    data = np.zeros((3, 4, 5), dtype=np.float32)
    a = np.eye(4)
    b = a.copy()
    b[0, 3] = 2
    nib.save(nib.Nifti1Image(data, a), tmp_path / "image.nii.gz")
    nib.save(nib.Nifti1Image(data, b), tmp_path / "ref.nii.gz")
    with pytest.raises(ValueError, match="grid mismatch"):
        load_case(tmp_path / "image.nii.gz", tmp_path / "ref.nii.gz")


def test_group_average_does_not_overweight_multiple_scans():
    scans = pd.DataFrame(
        {"sequence": ["T2"] * 3, "patient_group": ["A", "A", "B"], "dice": [0.2, 0.4, 0.9]}
    )
    result = study_summary(scans).iloc[0]
    assert result["group-mean Dice"] == pytest.approx(0.6)
    assert result["scan-mean Dice"] == pytest.approx(0.5)
    assert result["operational groups"] == 2


def _manifest(features=4, checkpoint=CHECKPOINT_SHA256):
    return {
        "schema_version": 1,
        "model": {"method": "SSC4", "input_features": features, "checkpoint_sha256": checkpoint},
        "cases": [
            {
                "case_id": "example",
                "sequence": "T1",
                "split": "development VAL",
                "selection": "Fixed illustration",
                "image": "image.nii.gz",
                "reference": "reference.nii.gz",
                "predictions": {"SSC4": {"label": 1, "path": "ssc4.nii.gz"}},
            }
        ],
    }


@pytest.mark.parametrize(
    ("features", "checkpoint"),
    [(8, CHECKPOINT_SHA256), (4, "old-checkpoint"), (8, "old-checkpoint")],
)
def test_stale_bundle_is_rejected_before_reading_scores(
    tmp_path, monkeypatch, features, checkpoint
):
    (tmp_path / "manifest.json").write_text(json.dumps(_manifest(features, checkpoint)))

    def forbidden(*args, **kwargs):
        raise AssertionError("Stale scores were read")

    monkeypatch.setattr(pd, "read_csv", forbidden)
    with pytest.raises(ValueError, match="Regenerate the SSC4"):
        load_demo(tmp_path)


def test_matching_ssc4_manifest_loads_without_reading_model_or_images(tmp_path):
    (tmp_path / "manifest.json").write_text(json.dumps(_manifest()))
    demo = load_demo(tmp_path)
    assert list(demo.cases.case_id) == ["example"]
    assert set(demo.row("example")["predictions"]) == {"SSC4"}


def test_untrusted_ssc4_checkpoint_is_rejected_before_pickle(tmp_path, monkeypatch):
    assert CHECKPOINT_SHA256 == "3ff24ee94d4f363348892d80f268fdea6904630a9639606a3b7ccd673ea4b922"
    (tmp_path / "fold_0").mkdir()
    (tmp_path / "plans.json").write_text("{}")
    (tmp_path / "dataset.json").write_text("{}")
    (tmp_path / "fold_0/checkpoint_final.pth").write_bytes(b"untrusted generated bytes")

    def forbidden(*args, **kwargs):
        raise AssertionError("Untrusted pickle was loaded")

    monkeypatch.setattr("ml_biomed_project.ssc.inference.torch.load", forbidden)
    with pytest.raises(ValueError, match="SHA256"):
        load_model(tmp_path, device="cpu")
